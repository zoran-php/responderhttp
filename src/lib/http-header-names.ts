// https://www.iana.org/assignments/http-fields/field-names.csv
//
// A committed constant rather than a build step: the registry changes a few
// times a year, and a generator plus a fetch at build time would be more
// moving parts than the problem has (CLAUDE.md section 7, YAGNI). To refresh,
// re-read the CSV and regenerate this list.
//
// Rust never needs these — header *names* are a UI affordance, not a rule the
// domain enforces — so unlike HTTP methods or content types this list lives
// only on the TS side and has no Rust counterpart to stay in step with.
//
// **The registry does not say which fields are requests and which are
// responses**; there is no such column. So this list includes response-only
// names such as Set-Cookie and WWW-Authenticate. That is deliberate: filtering
// them would be our invention rather than the registry's, and a request
// builder has no business refusing to suggest something IANA registered.
//
// Entries marked `obsoleted` or `deprecated` are left out (46 of
// 255), so Warning and Content-MD5 are not offered. Typing one still
// works — the field is free text, and autocomplete only ever suggests.
